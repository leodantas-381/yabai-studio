import Foundation

struct StartupPaths {
    let home: URL
    let support: URL
    let environment: [String:String]
    init(home: URL = FileManager.default.homeDirectoryForCurrentUser,
         support: URL = URL.applicationSupportDirectory.appendingPathComponent("YabaiStudio"),
         environment: [String:String] = ProcessInfo.processInfo.environment) {
        self.home = home; self.support = support; self.environment = environment
    }
    var script: URL { support.appendingPathComponent("startup.sh") }
    func config() throws -> URL {
        var env = environment
        for name in ["com.asmvik.yabai", "com.koekeishiya.yabai"] {
            let agent = home.appendingPathComponent("Library/LaunchAgents/\(name).plist")
            guard let data = try? Data(contentsOf: agent),
                  let plist = try? PropertyListSerialization.propertyList(from: data,format:nil) as? [String:Any] else { continue }
            if let values = plist["EnvironmentVariables"] as? [String:String] { env.merge(values) { _,new in new } }
            if let args = plist["ProgramArguments"] as? [String] {
                for (index,arg) in args.enumerated() {
                    if ["-c","--config"].contains(arg), index+1 < args.count {
                        guard args[index+1].hasPrefix("/") else { throw StartupError.failed("O serviço usa um caminho de configuração relativo. Selecione um caminho absoluto na configuração do serviço antes de salvar pelo Studio.") }
                        return URL(fileURLWithPath:args[index+1]).resolvingSymlinksInPath()
                    }
                    if arg.hasPrefix("--config=") {
                        let path=String(arg.dropFirst(9))
                        guard path.hasPrefix("/") else { throw StartupError.failed("O caminho de configuração do serviço precisa ser absoluto.") }
                        return URL(fileURLWithPath:path).resolvingSymlinksInPath()
                    }
                }
            }
        }
        var choices: [URL] = []
        if let xdg=env["XDG_CONFIG_HOME"], xdg.hasPrefix("/") { choices.append(URL(fileURLWithPath:xdg).appendingPathComponent("yabai/yabairc")) }
        choices.append(home.appendingPathComponent(".config/yabai/yabairc"))
        choices.append(home.appendingPathComponent(".yabairc"))
        return (choices.first {FileManager.default.fileExists(atPath:$0.path)} ?? choices[0]).resolvingSymlinksInPath()
    }
}
enum StartupError: LocalizedError {
    case failed(String)
    var errorDescription: String? { if case .failed(let text)=self { return text }; return nil }
}
struct StartupPersistence {
    static let begin = "# BEGIN YABAI STUDIO STARTUP"
    static let end = "# END YABAI STUDIO STARTUP"
    let paths: StartupPaths
    init(paths: StartupPaths = StartupPaths()) { self.paths=paths }
    static func script(binary: String, commands: [[String]]) -> String {
        "#!/bin/sh\n# Generated by Yabai Studio.\nset -e\n" + commands.map {
            ([binary]+$0).map(HotkeyConfig.quote).joined(separator:" ")
        }.joined(separator:"\n") + "\n"
    }
    static func updatedConfig(_ original: String, script: URL) throws -> String {
        if original.range(of: #"(?m)^[ \t]*(exit|exec|return)([ \t;]|$)"#, options:.regularExpression) != nil {
            throw StartupError.failed("O yabairc contém exit, exec ou return e pode terminar antes de carregar os ajustes. Use Exportar para integrar os ajustes manualmente ou remova essa saída antecipada da configuração.")
        }
        var base=original
        if let begin=base.range(of:Self.begin) {
            guard let end=base.range(of:Self.end,range:begin.upperBound..<base.endIndex) else { throw StartupError.failed("O bloco de inicialização do Studio está incompleto. Restaure o backup da configuração antes de salvar novamente.") }
            base.removeSubrange(begin.lowerBound..<end.upperBound)
            guard !base.contains(Self.begin), !base.contains(Self.end) else { throw StartupError.failed("Há mais de um bloco de inicialização do Studio. Revise a configuração antes de salvar.") }
        } else if base.contains(Self.end) { throw StartupError.failed("O bloco de inicialização do Studio está incompleto.") }
        if base.hasPrefix("#!"), let first=base.split(separator:"\n").first {
            let shell=first.lowercased()
            guard ["/sh","/bash","/zsh","/dash","/ksh","env sh","env bash","env zsh"].contains(where:shell.contains) else { throw StartupError.failed("O yabairc usa um interpretador que o Studio não pode modificar automaticamente. Use Exportar para integrar a configuração manualmente.") }
        }
        // Isolate errors from the user's shell options and run after existing commands.
        let quoted=HotkeyConfig.quote(script.path)
        let block="\(Self.begin)\nif [ -r \(quoted) ]; then\n    /bin/sh \(quoted) || /usr/bin/printf '%s\\n' 'Yabai Studio: falha ao carregar ajustes.' >&2\nfi\n\(Self.end)\n"
        return base.trimmingCharacters(in:.newlines) + (base.isEmpty ? "#!/bin/sh\n" : "\n\n") + block
    }
    func install(binary: String, commands: [[String]]) throws -> URL {
        let fm=FileManager.default
        let config=try paths.config()
        let existed=fm.fileExists(atPath:config.path)
        let permissions = existed ? (try fm.attributesOfItem(atPath: config.path)[.posixPermissions]) : nil
        let original=existed ? try String(contentsOf:config,encoding:.utf8) : ""
        let updated=try Self.updatedConfig(original,script:paths.script)
        let script=Self.script(binary:binary,commands:commands)
        try fm.createDirectory(at:paths.support,withIntermediateDirectories:true)
        try fm.createDirectory(at:config.deletingLastPathComponent(),withIntermediateDirectories:true)
        // Keep an exact, unique backup of every existing configuration before changing it.
        if existed {
            let backup=config.appendingPathExtension("studio-backup-"+UUID().uuidString)
            try fm.copyItem(at:config,to:backup)
        }
        let previous=try? Data(contentsOf:paths.script)
        do {
            try script.write(to:paths.script,atomically:true,encoding:.utf8)
            try updated.write(to:config,atomically:true,encoding:.utf8)
            if let permissions { try fm.setAttributes([.posixPermissions:permissions],ofItemAtPath:config.path) }
        } catch {
            if let previous { try? previous.write(to:paths.script,options:.atomic) }
            else { try? fm.removeItem(at:paths.script) }
            throw error
        }
        return config
    }
}
